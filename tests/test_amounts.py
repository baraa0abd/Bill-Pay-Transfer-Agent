import pytest
from agent.amounts import parse_amount, amount_words

@pytest.mark.parametrize('text,value', [('50000',50000),('50,000',50000),('٥٠ الف',50000),('خمسين ألف',50000),('ميت ألف',100000),('مية ألف',100000),('ربع مليون',250000),('نص مليون',500000),('مليون ونص',1500000),('مليونين',2000000),('ألفين',2000),('الف',1000),('عشرين الف',20000),('ثلاثين الف',30000),('اربعين الف',40000),('ستين الف',60000),('سبعين الف',70000),('ثمانين الف',80000),('تسعين الف',90000),('50 دينار',50),('٥۰٬۰۰۰',50000),('50000 د.ع',50000),('خمسة الاف',5000),('عشرة الاف',10000),('1000000',1000000),('مليون',1000000),('مئة الف',100000),('۲۵۰۰۰',25000)])
def test_valid(text,value):
    result=parse_amount(text)
    assert result.value==value and not result.ambiguous
    assert 'دينار' in amount_words(value)

@pytest.mark.parametrize('text', ['خمسين','50','٥٠','اربعين','2','0','-100','50.5','1,00','كم ورقه','دفتر','نص','abc','','عشرين ثلاثين','50 الف 20 الف','50000.0','1e5', 'نص ورقه','1000000001'])
def test_uncertain(text):
    assert parse_amount(text).ambiguous
